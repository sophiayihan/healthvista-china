  function syncInternalLinks(lang) {
    document.querySelectorAll('a[href]').forEach(function (a) {
      const raw = a.getAttribute('href');
      if (!raw || raw.startsWith('#') || raw.startsWith('http') || raw.startsWith('mailto:') || raw.startsWith('tel:')) return;
      try {
        const url = new URL(raw, window.location.href);
        if (url.origin !== window.location.origin) return;
        if (!url.pathname.endsWith('.html') && url.pathname !== '/' && url.pathname !== '') return;
        url.searchParams.set('lang', lang);
        a.setAttribute('href', url.pathname.split('/').pop() + url.search + url.hash);
      } catch (e) {}
    });
  }

  // ---------- Apply language ----------
  function applyLanguage(lang) {
    if (!dict[lang]) lang = 'en';
    const html = document.documentElement;
    html.lang = lang;
    html.dir = (lang === 'ar') ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const key = el.getAttribute('data-i18n');
      const value = dict[lang][key];
      if (value !== undefined) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = value;
        } else {
          el.textContent = value;
        }
      }
    });

    translateLooseText(lang);
    translateCommonChrome(lang);
    syncInternalLinks(lang);

    try { localStorage.setItem('jadebridge.lang', lang); } catch (e) {}
  }

